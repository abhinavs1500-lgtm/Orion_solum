from typing import List, Optional, Dict, Any
from datetime import datetime, timezone
from fastapi import APIRouter, HTTPException, Query, Depends, Request
from fastapi.responses import JSONResponse
from backend.models import (
    IssueResponse,
    OfficialUpdateCreate,
    AuditLogResponse,
    OfficialLoginRequest,
    OfficialAuthResponse,
    OfficialStatsResponse
)
from backend.services.issues_service import (
    get_prioritized_issues,
    get_official_dashboard_stats,
    apply_official_update,
    get_audit_logs,
    list_issues,
    get_issue_by_id
)
from backend.services.officials_auth import (
    authenticate_official,
    get_current_official,
    check_official_jurisdiction
)

router = APIRouter(prefix="/api/officials", tags=["Officials & Disaster Coordination"])

@router.post("/login", response_model=OfficialAuthResponse)
def official_login(request: OfficialLoginRequest):
    """Authenticates municipal/disaster officials and issues a signed session token."""
    return authenticate_official(request)

@router.get("/verify")
def verify_session(official: Dict[str, Any] = Depends(get_current_official)):
    """Validates the current official's session token and returns identity and jurisdiction."""
    return {
        "status": "authenticated",
        "active": True,
        "official_id": official.get("oid"),
        "name": official.get("name"),
        "role": official.get("role"),
        "district": official.get("district"),
        "expires_at": official.get("exp")
    }

@router.get("/priorities", response_model=List[IssueResponse])
def get_priorities(
    district: Optional[str] = Query(None, description="Filter priorities by district"),
    city: Optional[str] = Query(None, description="Filter priorities by city"),
    locality: Optional[str] = Query(None, description="Filter priorities by locality"),
    status: Optional[str] = Query("all", description="Filter by status ('all', 'open', 'Resolved')")
):
    """Returns dynamically ranked issues for the selected location."""
    return get_prioritized_issues(district=district, city=city, locality=locality, status=status)

@router.get("/stats", response_model=OfficialStatsResponse)
def get_stats(
    district: Optional[str] = Query(None, description="District scope for statistics"),
    city: Optional[str] = Query(None, description="City scope"),
    locality: Optional[str] = Query(None, description="Locality scope")
):
    """Returns real-time dashboard counts, costs, and progress metrics for the selected location."""
    return get_official_dashboard_stats(district=district, city=city, locality=locality)

@router.post("/updates", response_model=IssueResponse)
def post_update(
    update: OfficialUpdateCreate,
    official: Dict[str, Any] = Depends(get_current_official)
):
    """Publishes a verified progress update. Enforces role-based district jurisdiction."""
    # Check issue existence and jurisdiction
    issue = get_issue_by_id(update.issue_id)
    if not issue:
        raise HTTPException(status_code=404, detail=f"Issue {update.issue_id} not found")
        
    if not check_official_jurisdiction(official, issue.district):
        raise HTTPException(
            status_code=403,
            detail=f"Unauthorized jurisdiction: Official {official.get('name')} ({official.get('district')}) cannot modify issues in {issue.district}"
        )
        
    try:
        # Stamp update with authenticated role
        update.actor_role = f"{official.get('role')} ({official.get('name')})"
        return apply_official_update(update)
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Update failed: {str(e)}")

@router.get("/audit", response_model=List[AuditLogResponse])
def get_audit(limit: int = Query(15, ge=1, le=100)):
    return get_audit_logs(limit=limit)

@router.get("/plan/export")
def export_recovery_plan(
    available_funds: int = Query(1_000_000),
    available_crew: int = Query(24),
    district: Optional[str] = Query(None, description="Scope export to specific district")
):
    open_issues = list_issues(status="open", district=district)
    total_cost = sum(i.cost for i in open_issues)
    total_crew = sum(i.crew for i in open_issues)
    
    plan = {
        "title": f"SOLUM — Disaster Recovery Resource Plan ({district or 'All Tamil Nadu'})",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "district_scope": district or "All Tamil Nadu",
        "available_funds_inr": available_funds,
        "available_crew_members": available_crew,
        "estimated_total_cost_inr": total_cost,
        "estimated_total_crew_needed": total_crew,
        "funding_gap_inr": max(0, total_cost - available_funds),
        "crew_shortfall": max(0, total_crew - available_crew),
        "open_issues_count": len(open_issues),
        "advisory": "Generated by SOLUM Decision Support System. Requires field verification before deployment.",
        "prioritized_actions": [i.dict() for i in open_issues]
    }
    return JSONResponse(
        content=plan,
        headers={"Content-Disposition": f"attachment; filename=SOLUM-recovery-plan-{(district or 'all').lower()}.json"}
    )
